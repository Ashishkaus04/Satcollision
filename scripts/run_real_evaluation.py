#!/usr/bin/env python3
r"""
Run the three-scenario comparison on real orbital data and write it up.

Two runs, both from real CelesTrak catalogues (see
``scripts/run_cross_operator_backtest.py`` for how to fetch them):

1. **Split catalogue (headline)** — one real catalogue, its satellites
   assigned to two operators by NORAD parity, keeping only conjunctions
   that cross the assigned boundary. Real orbits and real encounter
   geometry; the ownership boundary is the assigned part.
2. **Cross-constellation** — two genuinely different operators,
   unmodified, reported with however many threshold crossings it finds.
   On most catalogues that is zero (which is why run 1 exists); when it is
   not, the write-up says so and treats the event as an existence proof
   rather than a statistic.

Usage:

    PYTHONPATH=src python3 scripts/run_real_evaluation.py \
        --catalog data/starlink.tle Starlink \
        --cross data/kuiper.tle Kuiper \
        --hours 168

Writes ``docs/real_evaluation.md`` (a report-ready section) and
``docs/figures/real_evaluation.json`` (the data behind it, and the input to
``scripts/make_figures.py``'s real-evaluation figure). A week-long window
over ~11,000 objects takes a few minutes; pass ``--hours 24`` for a quick
pass.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DOC_PATH = REPO_ROOT / "docs" / "real_evaluation.md"
JSON_PATH = REPO_ROOT / "docs" / "figures" / "real_evaluation.json"


def _check(path: str) -> str:
    p = Path(path)
    if not p.exists() or p.stat().st_size == 0:
        print(f"ERROR: {path} does not exist or is empty.")
        print("See scripts/run_cross_operator_backtest.py's docstring for how to fetch a TLE file.")
        sys.exit(1)
    return path


def _summary_table(summary: dict) -> str:
    if not summary.get("n_encounters"):
        return "_No conjunction crossed the operational risk threshold in this run._\n"
    exposure = summary["raw_data_exposed_pct"]
    return (
        "| Scenario | Median detection lead time | Raw trajectory data exposed | Cross-operator signal |\n"
        "|---|---|---|---|\n"
        f"| No Cooperation | {summary['median_lead_time_nocoop_h']:.1f} h | "
        f"{exposure['no_cooperation']:.0f}% | no |\n"
        f"| Full Data Sharing | {summary['median_lead_time_cooperative_h']:.1f} h | "
        f"{exposure['full_sharing']:.0f}% | yes |\n"
        f"| **Federated (proposed)** | **{summary['median_lead_time_cooperative_h']:.1f} h** | "
        f"**{exposure['federated']:.0f}%** | yes |\n"
    )


def _encounter_table(rows: list[dict], limit: int = 15) -> str:
    if not rows:
        return ""
    ranked = sorted(rows, key=lambda r: -r["pc"])[:limit]
    lines = [
        "| Encounter | Miss (m) | Pc | Geometry | Lead time, no cooperation | Lead time, federated | Gain |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in ranked:
        lines.append(
            f"| `{r['encounter_id']}` | {r['miss_distance_m']:.0f} | {r['pc']:.2e} | "
            f"{r['geometry_class']} | {r['lead_time_nocoop_min'] / 60:.1f} h | "
            f"{r['lead_time_cooperative_min'] / 60:.1f} h | +{r['lead_time_gain_min'] / 60:.1f} h |"
        )
    if len(rows) > limit:
        lines.append(f"\n_{len(rows)} encounters in total; the {limit} highest-Pc are shown._")
    return "\n".join(lines) + "\n"


def _render_markdown(headline: dict, negative: dict | None) -> str:
    s = headline["summary"]
    parts = [
        "# Three-scenario comparison on real orbital data",
        "",
        f"_Generated by `scripts/run_real_evaluation.py` on {headline['computed_at_utc']}._",
        "",
        "## Method, and what is real in it",
        "",
        f"Every orbit, miss distance, time-to-closest-approach and collision probability below comes "
        f"from a real {headline['catalog']} catalogue ({headline['n_objects']:,} objects), propagated "
        f"with SGP4 across a {headline['window_hours']:.0f}-hour window at a {headline['step_s']:.0f}-second "
        f"step and screened at {headline['screening_km']:.0f} km. Detection lead time is measured inside a "
        f"rolling {headline['screening_horizon_h']:.0f}-hour screening horizon, the window inside which "
        "operators actually screen conjunctions and decide on maneuvers.",
        "",
        "The one assigned element is **ownership**: satellites are split between two operators by "
        f"{headline['ownership']}. This is necessary and is stated rather than hidden: genuine "
        "cross-operator threshold crossings are rare enough that no useful distribution can be built "
        "from them (see the second run below for what a real catalogue actually contains). Catalogue "
        "numbers track launch order, so parity is uncorrelated with orbital shell; splitting by "
        "altitude instead would have drawn the boundary along a line the orbits themselves respect, "
        "and produced an empty result by construction.",
        "",
        f"Because cooperation flags an encounter as soon as it enters that horizon, the cooperative "
        f"lead time saturates at {headline['screening_horizon_h']:.0f} hours; the quantity that actually "
        "varies across encounters — and therefore the one the figure plots — is how much later "
        "no-cooperation gets there.",
        "",
        "A caveat worth keeping in the text: full-sharing and federated produce the *same* detection "
        "lead time by design — in both, each operator tracks its own asset at full precision and learns "
        "of the encounter in time to act. That equality is an architectural property, not a measurement. "
        "What the real data measures is the quantity that genuinely varies: how much warning "
        "no-cooperation loses across real encounter geometries.",
        "",
        "## Headline result",
        "",
        f"Of {headline['n_conjunctions_screened']:,} screened conjunctions, "
        f"{headline['n_cross_operator']:,} crossed the assigned operator boundary and "
        f"**{headline['n_above_threshold']:,}** crossed the operational risk threshold "
        f"(Pc >= {headline['pc_threshold']:.0e}).",
        "",
        (f"Of those, {headline.get('n_excluded_burn_in', 0):,} are excluded and "
         f"**{headline.get('n_scored', headline['n_above_threshold']):,}** scored: an encounter whose "
         f"closest approach falls inside the first {headline['screening_horizon_h']:.0f} hours of the "
         "propagation window has its warning time clipped by when the window opened rather than by "
         "tracking quality, identically in every scenario, so it carries no information about what "
         "cooperation buys."
         if headline.get('n_excluded_burn_in') else ""),
        "",
        _summary_table(s),
    ]

    if s.get("n_encounters"):
        parts += [
            f"Across those {s['n_encounters']} real encounters, cooperation bought a median of "
            f"**{s['median_lead_time_gain_h']:.1f} hours** of extra warning "
            f"(mean {s['mean_lead_time_gain_h']:.1f} h), at zero exposure of raw trajectory data. "
            f"No-cooperation's own warning time ranged from {s['min_lead_time_nocoop_h']:.1f} to "
            f"{s['max_lead_time_nocoop_h']:.1f} hours. "
            + (f"{s['n_missed_entirely_by_nocoop']} of them ({s['pct_missed_entirely_by_nocoop']:.1f}%) "
               f"were never detected at all under no-cooperation before closest approach."
               if s["n_missed_entirely_by_nocoop"] else
               "Every encounter was eventually detected under no-cooperation, just later."),
            "",
            f"Median miss distance across the set: {s['median_miss_distance_m']:.0f} m.",
            "",
            "### Per-encounter detail",
            "",
            _encounter_table(headline["encounters"]),
        ]

    if negative is not None:
        n = negative["summary"]
        closest = negative["closest_cross_operator_km"]
        found = int(negative["n_above_threshold"])
        crossing_word = "crossing" if found == 1 else "crossings"
        head_line = (
            f"The same pipeline across {negative['catalog']} — {negative['n_objects']:,} real objects, "
            f"genuine ownership, nothing assigned — over the same {negative['window_hours']:.0f}-hour "
            f"window found **{found} threshold {crossing_word}** out of "
            f"{negative['n_cross_operator']:,} cross-operator close approaches"
            + (f", the closest passing {closest * 1000:.0f} m apart "
               f"(highest Pc {negative['max_cross_operator_pc']:.1e})." if closest is not None
               else "; no pair came within the screening volume at all.")
        )

        if found:
            # The motivating scenario is not hypothetical on this catalogue: it
            # happened. Say so, and be equally clear about what one event can
            # and cannot support.
            parts += [
                "",
                "## Genuine cross-operator encounters, with no assignment at all",
                "",
                head_line,
                "",
                "This is the scenario the whole project is premised on, occurring between two real "
                "operators in a real catalogue — measured rather than assumed. It is worth stating "
                "plainly what it does and does not establish: one event is an existence proof, not a "
                "distribution. It cannot support a median, a spread, or any claim about how much "
                "warning cooperation buys *in general*, which is exactly why the split-catalogue run "
                "above exists and carries the statistics. Read together, the two runs say: the "
                "encounter type is real, and here is what the system does across hundreds of them.",
                "",
                "Whether a given week contains such an encounter depends on the catalogue of the day, "
                "so a re-run may find none — which is itself the honest characterisation of how rare "
                "these events currently are.",
                "",
                "### The encounter(s) found",
                "",
                _encounter_table(negative["encounters"]),
                "",
            ]
        else:
            parts += [
                "",
                "## The negative result this rests on",
                "",
                head_line,
                "",
                "This is a real property of today's sky rather than a limitation of the method: "
                "megaconstellations are deliberately placed in separated altitude shells, so genuine "
                "cross-operator threshold crossings are rare events. It is also the reason a federated "
                "system has to be evaluated on an assigned boundary today — and the reason such a system "
                "matters as more operators occupy overlapping shells.",
                "",
            ]

    command = ["PYTHONPATH=src python3 scripts/run_real_evaluation.py \\",
               f"    --catalog data/{headline['catalog'].lower()}.tle {headline['catalog']} \\"]
    if negative is not None:
        other = negative["catalog"].split(" x ")[-1]
        command.append(f"    --cross data/{other.lower()}.tle {other} \\")
    command.append(f"    --hours {headline['window_hours']:.0f}")

    parts += [
        "## Reproducing this",
        "",
        "```bash",
        *command,
        "```",
        "",
        "TLE files are republished daily, so re-running will produce a different (equally real) set of "
        "encounters. `docs/figures/real_evaluation.json` holds the exact data behind this document.",
        "",
    ]
    return "\n".join(p for p in parts if isinstance(p, str))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--catalog", nargs=2, metavar=("TLE", "NAME"), required=True,
                        help="real catalogue to split into two operators (headline run)")
    parser.add_argument("--cross", nargs=2, metavar=("TLE", "NAME"), default=None,
                        help="second real catalogue, for the genuine cross-operator negative")
    parser.add_argument("--hours", type=float, default=168.0, help="propagation window (default 168)")
    parser.add_argument("--step", type=float, default=30.0, help="propagation step in seconds")
    parser.add_argument("--rerender", action="store_true",
                        help="rebuild docs/real_evaluation.md from the existing JSON without "
                             "re-running the propagation (for wording changes)")
    args = parser.parse_args()

    if args.rerender:
        if not JSON_PATH.exists():
            print(f"ERROR: {JSON_PATH} not found — run without --rerender first.")
            return 1
        cached = json.loads(JSON_PATH.read_text(encoding="utf-8"))
        DOC_PATH.write_text(_render_markdown(cached["headline"], cached.get("negative")),
                            encoding="utf-8")
        print(f"Re-rendered {DOC_PATH.relative_to(REPO_ROOT)} from the cached run "
              f"({cached['headline']['computed_at_utc']}).")
        return 0

    from satcollision.real_evaluation import (
        run_cross_constellation_evaluation, run_split_catalog_evaluation,
    )

    tle_a, name_a = _check(args.catalog[0]), args.catalog[1]
    print(f"[1/2] Split-catalogue run: {name_a}, {args.hours:.0f}h window ...")
    headline = run_split_catalog_evaluation(tle_a, catalog_name=name_a, hours=args.hours,
                                             step_s=args.step)
    s = headline["summary"]
    print(f"      {headline['n_objects']:,} objects, {headline['n_cross_operator']:,} cross-operator "
          f"close approaches, {headline['n_above_threshold']} above threshold "
          f"({headline['n_scored']} scored, {headline['n_excluded_burn_in']} inside the burn-in window)")
    if s.get("n_encounters"):
        print(f"      median lead time: no-cooperation {s['median_lead_time_nocoop_min']:.2f} min "
              f"vs federated {s['median_lead_time_cooperative_min']:.2f} min "
              f"(median gain {s['median_lead_time_gain_min']:.2f} min)")

    negative = None
    if args.cross:
        tle_b, name_b = _check(args.cross[0]), args.cross[1]
        print(f"[2/2] Cross-constellation run: {name_a} x {name_b} ...")
        negative = run_cross_constellation_evaluation(tle_a, name_a, tle_b, name_b,
                                                       hours=args.hours, step_s=args.step)
        print(f"      {negative['n_cross_operator']:,} genuine cross-operator close approaches, "
              f"{negative['n_above_threshold']} above threshold"
              + (f", closest {negative['closest_cross_operator_km'] * 1000:.0f} m"
                 if negative["closest_cross_operator_km"] is not None else ""))
    else:
        print("[2/2] Cross-constellation run skipped (no --cross given)")

    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_text(json.dumps({"headline": headline, "negative": negative}, indent=2),
                         encoding="utf-8")
    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text(_render_markdown(headline, negative), encoding="utf-8")
    print(f"\nWrote {DOC_PATH.relative_to(REPO_ROOT)} and {JSON_PATH.relative_to(REPO_ROOT)}")
    print("Then: PYTHONPATH=src python3 scripts/make_figures.py --real-evaluation")
    return 0


if __name__ == "__main__":
    sys.exit(main())
