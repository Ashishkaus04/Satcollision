#!/usr/bin/env python3
r"""
Replay a documented real close approach and report whether, and how early,
the pipeline would have flagged it. See src/satcollision/historical_replay.py
for the method and what it does and does not claim.

Getting the data (needs a free Space-Track account; CelesTrak only serves
current element sets):

1. Log in at https://www.space-track.org and open "Query Builder".
2. Class: gp_history. NORAD_CAT_ID: both objects (e.g. 48274 for the China
   Space Station and the Starlink satellite's number). EPOCH: a range from
   about 5 days before the event to the event day. Format: 3LE.
3. Save the result as data/historical/<event>.tle (one file holding the
   history of both objects is fine).

Usage:

    PYTHONPATH=src python scripts/run_historical_replay.py --list

    PYTHONPATH=src python scripts/run_historical_replay.py \
        --event css-starlink1095-2021 --tle data/historical/css_1095.tle \
        --tca 2021-07-01T13:00

    # any other pair: give both NORAD numbers and the documented time
    PYTHONPATH=src python scripts/run_historical_replay.py \
        --tle my_history.tle --norad 48274 12345 --tca 2021-10-21T12:00 --name my-event

``--tca`` overrides the registry's placeholder time: take the exact time from
the cited source before quoting a lead time.

Writes docs/historical_replay_<event>.md and docs/figures/historical_replay_<event>.json.
"""
from __future__ import annotations

import argparse
import datetime
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


def _render(event_title, source, result, rows, summary) -> str:
    lines = [
        f"# Historical replay: {event_title}",
        "",
        f"_Generated by `scripts/run_historical_replay.py` on "
        f"{datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds')}._",
        "",
        f"Documented closest approach: **{result.documented_tca_utc.isoformat(timespec='minutes')}** "
        f"(NORAD {result.norad_a} vs {result.norad_b}).",
        "",
        f"Source: {source}" if source else "",
        "",
        f"**Outcome:** {summary}",
        "",
        "Each row screens the pair using only the element sets that had been published by its "
        "as-of time, then propagates to just after the documented approach.",
        "",
        "| As of (h before) | Element-set epochs used (A / B) | Predicted TCA | Miss (m) | Pc | Flagged |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['hours_before']:.0f} | {r['element_set_epoch_a'] or '—'} / "
            f"{r['element_set_epoch_b'] or '—'} | {r['predicted_tca_utc'] or '—'} | "
            f"{r['miss_distance_m'] if r['miss_distance_m'] is not None else '—'} | "
            f"{r['pc']:.1e} | {'yes' if r['flagged'] else 'no'}"
            + (f" ({r['note']})" if r['note'] else "") + " |"
        )
    lines += [
        "",
        f"Threshold Pc {result.threshold:.0e}, circular Pc model, 1-second propagation grid.",
        "",
        "A documented event is usually a predicted approach that one side then manoeuvred away "
        "from, so the replay is checking the prediction an operator would have had, not the "
        "physical outcome.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    from satcollision.fleets import load_tle_file
    from satcollision.historical_replay import (
        DEFAULT_AS_OF_HOURS, EVENTS, describe, find_norad_by_name, replay_event,
    )

    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--list", action="store_true", help="list the documented events")
    parser.add_argument("--event", choices=sorted(EVENTS), help="documented event to replay")
    parser.add_argument("--tle", nargs="+", help="TLE history file(s) covering both objects")
    parser.add_argument("--norad", nargs=2, type=int, metavar=("A", "B"),
                        help="NORAD numbers (overrides the event's)")
    parser.add_argument("--tca", help="documented TCA, ISO UTC, e.g. 2021-07-01T13:00")
    parser.add_argument("--name", help="output name when not using --event")
    parser.add_argument("--as-of", nargs="+", type=float, default=list(DEFAULT_AS_OF_HOURS),
                        help="hours before TCA to screen from (default 72 48 24 12 6)")
    args = parser.parse_args()

    if args.list:
        for event in EVENTS.values():
            print(f"{event.key}\n  {event.title}\n  source: {event.source}\n  {event.notes}\n")
        return 0
    if not args.tle:
        parser.error("--tle is required (see the docstring for how to download a history)")

    objects = []
    for path in args.tle:
        if not Path(path).exists():
            print(f"ERROR: {path} not found. See this script's docstring for how to get it.")
            return 1
        objects += load_tle_file(path, operator_name=Path(path).stem)

    event = EVENTS.get(args.event) if args.event else None
    if args.norad:
        norad_a, norad_b = args.norad
    elif event:
        norad_a = event.norad_a or find_norad_by_name(objects, event.name_a)
        norad_b = event.norad_b or find_norad_by_name(objects, event.name_b)
        if norad_a is None or norad_b is None:
            print(f"ERROR: could not find {event.name_a!r} / {event.name_b!r} in the TLE file by "
                  "name; pass --norad A B.")
            return 1
    else:
        parser.error("give --event or --norad")

    if args.tca:
        tca = datetime.datetime.fromisoformat(args.tca)
        tca = tca if tca.tzinfo else tca.replace(tzinfo=datetime.timezone.utc)
    elif event:
        tca = event.tca_utc
        print(f"NOTE: using the registry's placeholder time {tca.isoformat()} — {event.notes}")
    else:
        parser.error("--tca is required without --event")

    # Give each object a distinct operator so the pair is screened as cross-operator.
    for o in objects:
        o.operator = "A" if o.norad_id == norad_a else "B"

    result = replay_event(objects, norad_a, norad_b, tca, as_of_hours=args.as_of)
    rows = [r.as_row() for r in result.rows]
    summary = describe(result)
    for r in rows:
        print(f"  T-{r['hours_before']:>4.0f} h  miss {r['miss_distance_m']} m  Pc {r['pc']:.1e}  "
              f"flagged={r['flagged']}  {r['note']}")
    print(summary)

    name = args.event or args.name or f"{norad_a}_{norad_b}"
    json_path = REPO_ROOT / "docs" / "figures" / f"historical_replay_{name}.json"
    doc_path = REPO_ROOT / "docs" / f"historical_replay_{name}.md"
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps({
        "event": name, "norad_a": norad_a, "norad_b": norad_b,
        "documented_tca_utc": tca.isoformat(), "summary": summary, "rows": rows,
    }, indent=2), encoding="utf-8")
    doc_path.write_text(_render(event.title if event else name, event.source if event else "",
                                result, rows, summary), encoding="utf-8")
    print(f"Wrote {doc_path.relative_to(REPO_ROOT)} and {json_path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
